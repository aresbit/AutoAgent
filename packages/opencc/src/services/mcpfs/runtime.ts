/**
 * The sandbox side of the MCP gateway, written next to the generated bindings
 * as servers/_mcpfs.ts and servers/_mcpfs.py.
 *
 * Code in a CodeAct sandbox never speaks MCP. It sends one JSON line per
 * request to the host's gateway (address and per-run token in the environment)
 * and the host performs the call on its live, authenticated connection — so
 * server-side state (an open binary, a database handle) survives between calls
 * and between runs, exactly as it does for the model's own MCP tool calls.
 *
 * Results come back raw: no truncation, no "saved to file" substitution. Large
 * results are the reason to call a tool from code in the first place.
 *
 * Result contract, both languages:
 *   tool declares an outputSchema  → the structured object, typed by it
 *   otherwise                      → { text, json, content } (ToolOutput in Python)
 *   tool reports isError           → throws McpToolError
 */

export const TS_CLIENT = `// Generated by opencc — sandbox side of the MCP gateway. Do not edit.
import { createConnection } from 'node:net'

export type McpContentBlock = { type: string; [key: string]: unknown }

/** What a tool without an outputSchema returns. */
export type McpToolOutput = {
  /** Every text block, joined with newlines. */
  text: string
  /** \`text\` parsed as JSON when it is JSON, otherwise undefined. */
  json: unknown
  /** The raw MCP content blocks (text, image, resource, resource_link, ...). */
  content: McpContentBlock[]
  structured?: Record<string, unknown>
}

export class McpToolError extends Error {
  constructor(
    message: string,
    readonly code: string,
    readonly server?: string,
    readonly tool?: string,
    readonly content?: McpContentBlock[],
  ) {
    super(message)
    this.name = 'McpToolError'
  }
}

function request(payload: Record<string, unknown>): Promise<any> {
  const address = process.env.OPENCC_MCP_GATEWAY
  const token = process.env.OPENCC_MCP_TOKEN
  if (!address || !token) {
    return Promise.reject(
      new McpToolError('No MCP gateway in this environment: run the code through opencc CodeAct.', 'no_gateway'),
    )
  }
  const colon = address.lastIndexOf(':')
  return new Promise((resolve, reject) => {
    const socket = createConnection({ host: address.slice(0, colon), port: Number(address.slice(colon + 1)) })
    let data = ''
    socket.setEncoding('utf8')
    socket.on('connect', () => socket.write(JSON.stringify({ token, ...payload }) + '\\n'))
    socket.on('data', (chunk: string) => { data += chunk })
    socket.on('error', reject)
    socket.on('end', () => {
      let reply: any
      try {
        reply = JSON.parse(data)
      } catch {
        reject(new McpToolError('Malformed reply from the MCP gateway.', 'protocol'))
        return
      }
      if (reply.ok) resolve(reply.result)
      else reject(new McpToolError(reply.error ?? 'MCP gateway error', reply.code ?? 'error', payload.server as string, payload.tool as string))
    })
  })
}

function toOutput(result: any): McpToolOutput {
  const content: McpContentBlock[] = Array.isArray(result?.content) ? result.content : []
  const text = content.filter(block => block.type === 'text').map(block => String(block.text ?? '')).join('\\n')
  let json: unknown
  try {
    json = text.trim() ? JSON.parse(text) : undefined
  } catch {
    json = undefined
  }
  return { text, json, content, ...(result?.structuredContent ? { structured: result.structuredContent } : {}) }
}

/** Call \`tool\` on \`server\` through the host's live MCP connection. */
export async function callMCPTool<T = McpToolOutput>(
  server: string,
  tool: string,
  args: Record<string, unknown> = {},
  options: { structured?: boolean } = {},
): Promise<T> {
  const result = await request({ op: 'call', server, tool, args })
  if (result?.isError) {
    const out = toOutput(result)
    throw new McpToolError(out.text || \`\${server}/\${tool} reported an error\`, 'tool_error', server, tool, out.content)
  }
  if (options.structured) {
    if (result?.structuredContent !== undefined) return result.structuredContent as T
    const out = toOutput(result)
    if (out.json !== undefined) return out.json as T
  }
  return toOutput(result) as T
}

/** resources/read on \`server\`: \`{ contents: [{ uri, mimeType, text | blob }] }\`. */
export function readResource(server: string, uri: string): Promise<{ contents: Array<Record<string, unknown>> }> {
  return request({ op: 'read_resource', server, uri })
}

/** resources/list on \`server\`. */
export function listResources(server: string): Promise<{ resources: Array<Record<string, unknown>> }> {
  return request({ op: 'list_resources', server })
}

/** prompts/get on \`server\`: \`{ description?, messages }\`. */
export function getPrompt(server: string, name: string, args: Record<string, string> = {}): Promise<{ messages: unknown[]; description?: string }> {
  return request({ op: 'get_prompt', server, name, args })
}
`

export const PY_CLIENT = `"""Generated by opencc — sandbox side of the MCP gateway. Do not edit."""
import json as _json
import os
import socket


class McpToolError(Exception):
    def __init__(self, message, code="error", server=None, tool=None, content=None):
        super().__init__(message)
        self.code = code
        self.server = server
        self.tool = tool
        self.content = content or []


class ToolOutput:
    """What a tool without an outputSchema returns."""

    __slots__ = ("text", "content", "structured")

    def __init__(self, result):
        self.content = list((result or {}).get("content") or [])
        self.text = "\\n".join(str(b.get("text", "")) for b in self.content if b.get("type") == "text")
        self.structured = (result or {}).get("structuredContent")

    @property
    def json(self):
        """\`text\` parsed as JSON, or None when it is not JSON."""
        try:
            return _json.loads(self.text) if self.text.strip() else None
        except ValueError:
            return None

    def __repr__(self):
        preview = self.text if len(self.text) <= 200 else self.text[:200] + "…"
        return f"ToolOutput(text={preview!r}, blocks={len(self.content)})"


def _request(payload):
    address = os.environ.get("OPENCC_MCP_GATEWAY")
    token = os.environ.get("OPENCC_MCP_TOKEN")
    if not address or not token:
        raise McpToolError("No MCP gateway in this environment: run the code through opencc CodeAct.", "no_gateway")
    host, port = address.rsplit(":", 1)
    with socket.create_connection((host, int(port))) as sock:
        sock.sendall((_json.dumps({"token": token, **payload}) + "\\n").encode("utf-8"))
        chunks = []
        while True:
            chunk = sock.recv(65536)
            if not chunk:
                break
            chunks.append(chunk)
    try:
        reply = _json.loads(b"".join(chunks).decode("utf-8"))
    except ValueError:
        raise McpToolError("Malformed reply from the MCP gateway.", "protocol")
    if not reply.get("ok"):
        raise McpToolError(reply.get("error") or "MCP gateway error", reply.get("code") or "error", payload.get("server"), payload.get("tool"))
    return reply.get("result")


def call_tool(server, tool, args=None, structured=False):
    """Call \`tool\` on \`server\` through the host's live MCP connection."""
    result = _request({"op": "call", "server": server, "tool": tool, "args": args or {}})
    if (result or {}).get("isError"):
        out = ToolOutput(result)
        raise McpToolError(out.text or f"{server}/{tool} reported an error", "tool_error", server, tool, out.content)
    if structured:
        if (result or {}).get("structuredContent") is not None:
            return result["structuredContent"]
        parsed = ToolOutput(result).json
        if parsed is not None:
            return parsed
    return ToolOutput(result)


def read_resource(server, uri):
    """resources/read on \`server\`: {"contents": [{uri, mimeType, text | blob}]}."""
    return _request({"op": "read_resource", "server": server, "uri": uri})


def list_resources(server):
    """resources/list on \`server\`."""
    return _request({"op": "list_resources", "server": server})


def get_prompt(server, name, args=None):
    """prompts/get on \`server\`: {"description"?, "messages"}."""
    return _request({"op": "get_prompt", "server": server, "name": name, "args": args or {}})
`
